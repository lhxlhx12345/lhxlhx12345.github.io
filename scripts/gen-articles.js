function ensureDir(dir) {
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
}

function renderToc(toc) {
  return toc.map((t, i) => `<li><a href="#sec-${i}" class="text-white/50 hover:text-purple-400 transition-colors">${t}</a></li>`).join('\n            ');
}

function renderSections(sections) {
  return sections.map((s, i) => `
        <section id="sec-${i}" class="scroll-mt-20">
            <h2 class="reveal text-2xl sm:text-3xl font-bold text-white mb-4 pb-3 border-b border-white/[0.06]">
                <span class="text-purple-400">${i + 1}.</span> ${s.h2}
            </h2>
            ${s.body}
        </section>`).join('\n    <!-- 分隔 -->\n');
}

